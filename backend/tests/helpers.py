from sqlalchemy import select, update

from app.db import SessionLocal
from app.models import SessionRecord, User

PASSWORD = "correct-horse-battery"


def register(client, email: str, name: str = "Test User") -> dict:
    r = client.post("/auth/register", json={"email": email, "password": PASSWORD, "full_name": name})
    assert r.status_code == 201, r.text
    return r.json()


def login(client, email: str) -> str:
    r = client.post("/auth/login", json={"email": email, "password": PASSWORD})
    assert r.status_code == 200, r.text
    return r.json()["access_token"]


def auth(token: str) -> dict:
    return {"Authorization": f"Bearer {token}"}


def user_token(client, email: str) -> str:
    register(client, email)
    return login(client, email)


def make_platform_admin(email: str) -> None:
    with SessionLocal() as db:
        db.execute(update(User).where(User.email == email).values(is_platform_admin=True))
        db.commit()


def expire_sessions_for(email: str) -> None:
    from datetime import UTC, datetime, timedelta

    with SessionLocal() as db:
        user = db.scalar(select(User).where(User.email == email))
        db.execute(
            update(SessionRecord)
            .where(SessionRecord.user_id == user.id)
            .values(expires_at=datetime.now(UTC) - timedelta(minutes=1))
        )
        db.commit()


def make_pdf(pages: list[str]) -> bytes:
    """A minimal, real PDF carrying the given text, one entry per page.

    Handwritten rather than generated by a library so the document tests depend on
    nothing beyond pypdf (which the app already needs to read these files). An empty
    string produces a page with no text layer, which is what a scan looks like.
    """
    def esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace("(", "\(").replace(")", "\)")

    body: dict[int, str] = {}
    page_ids: list[int] = []
    num = 3
    for text in pages:
        lines = text.split("\n") if text else []
        stream = (
            "BT /F1 12 Tf\n"
            + "".join(f"1 0 0 1 72 {760 - i * 16} Tm ({esc(line)}) Tj\n" for i, line in enumerate(lines))
            + "ET"
        )
        pid, cid = num, num + 1
        num += 2
        page_ids.append(pid)
        body[pid] = (
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << "
            f"/F1 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> >> >> /Contents {cid} 0 R >>"
        )
        body[cid] = f"<< /Length {len(stream)} >>\nstream\n{stream}\nendstream"

    body[1] = "<< /Type /Catalog /Pages 2 0 R >>"
    body[2] = f"<< /Type /Pages /Kids [{' '.join(f'{p} 0 R' for p in page_ids)}] /Count {len(page_ids)} >>"

    out = "%PDF-1.4\n"
    offsets: dict[int, int] = {}
    for key in sorted(body):
        offsets[key] = len(out)
        out += f"{key} 0 obj\n{body[key]}\nendobj\n"
    xref = len(out)
    size = max(body) + 1
    out += f"xref\n0 {size}\n0000000000 65535 f \n"
    for key in range(1, size):
        out += f"{offsets.get(key, 0):010d} 00000 n \n"
    out += f"trailer\n<< /Size {size} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n"
    return out.encode("latin-1")
