"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { FormEvent, useCallback, useEffect, useState } from "react";
import { Notice } from "@/components/Notice";
import { ReviewBadge } from "@/components/ReviewBadge";
import { api, ApiError, clearToken, getToken } from "@/lib/api";
import type { Decision, PanVerification } from "@/lib/types";

const ACCEPT = "application/pdf,image/jpeg,image/png,.pdf,.jpg,.jpeg,.png";
const PAN_PATTERN = /^[A-Za-z]{5}[0-9]{4}[A-Za-z]$/;

function formatSize(bytes: number): string {
  return bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))} KB` : `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function formatDate(iso: string): string {
  return new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" });
}

function statusCopy(sub: PanVerification): string {
  if (sub.review_status === "PENDING_REVIEW") return "Imparency has not checked this submission yet.";
  if (sub.review_status === "APPROVED") {
    return sub.latest_decision ? `Reviewed and approved on ${formatDate(sub.latest_decision.decided_at)}.` : "Reviewed and approved.";
  }
  return "Not accepted. Read the reviewer's note, then submit again with a corrected file.";
}

export default function PanVerificationPage() {
  const router = useRouter();
  const [subs, setSubs] = useState<PanVerification[] | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);

  const [panNumber, setPanNumber] = useState("");
  const [file, setFile] = useState<File | null>(null);
  const [uploading, setUploading] = useState(false);
  const [uploadOk, setUploadOk] = useState<string | null>(null);
  const [uploadError, setUploadError] = useState<string | null>(null);
  const [fileInputKey, setFileInputKey] = useState(0);

  const [history, setHistory] = useState<Record<string, Decision[] | "loading" | "error">>({});

  const load = useCallback(async () => {
    try {
      setSubs(await api<PanVerification[]>("/me/pan-verification"));
      setLoadError(null);
    } catch (err) {
      if (err instanceof ApiError && err.status === 401) {
        clearToken();
        router.replace("/login");
        return;
      }
      setLoadError(err instanceof Error ? err.message : "Could not load your PAN verification status.");
    }
  }, [router]);

  useEffect(() => {
    if (!getToken()) {
      router.replace("/login");
      return;
    }
    load();
  }, [load, router]);

  async function onUpload(e: FormEvent) {
    e.preventDefault();
    const pan = panNumber.trim().toUpperCase();
    if (!PAN_PATTERN.test(pan)) {
      setUploadError("Enter a valid PAN in the format ABCDE1234F.");
      return;
    }
    if (!file) {
      setUploadError("Choose a PDF, JPEG or PNG scan of your PAN card.");
      return;
    }
    setUploading(true);
    setUploadOk(null);
    setUploadError(null);
    try {
      const form = new FormData();
      form.set("pan_number", pan);
      form.set("file", file);
      await api<PanVerification>("/me/pan-verification", { method: "POST", body: form });
      setUploadOk("Submitted. It is now awaiting review by Imparency.");
      setPanNumber("");
      setFile(null);
      setFileInputKey((k) => k + 1);
      await load();
    } catch (err) {
      setUploadError(err instanceof Error ? err.message : "Submission failed. Try again.");
    } finally {
      setUploading(false);
    }
  }

  async function toggleHistory(sub: PanVerification) {
    if (history[sub.id] && history[sub.id] !== "error") {
      setHistory((h) => {
        const next = { ...h };
        delete next[sub.id];
        return next;
      });
      return;
    }
    setHistory((h) => ({ ...h, [sub.id]: "loading" }));
    try {
      const rows = await api<Decision[]>(`/me/pan-verification/${sub.id}/decisions`);
      setHistory((h) => ({ ...h, [sub.id]: rows }));
    } catch {
      setHistory((h) => ({ ...h, [sub.id]: "error" }));
    }
  }

  if (loadError) return <Notice kind="error">{loadError}</Notice>;
  if (!subs) return <p className="text-muted">Loading your PAN verification status…</p>;

  const isVerified = subs.some((s) => s.review_status === "APPROVED");
  const hasPending = subs.some((s) => s.review_status === "PENDING_REVIEW");

  return (
    <div className="space-y-8">
      <header className="space-y-2">
        <h1 className="text-2xl font-semibold text-navy">PAN verification</h1>
        <p className="max-w-2xl text-sm text-muted">
          Verifying your PAN lets Imparency email you a tax (80G) certificate for every donation you make. This is
          private and checked by a reviewer, not generated by a machine. Donating does not require this, but receiving
          a tax certificate does.
        </p>
        <Link href="/dashboard" className="text-sm text-teal hover:underline">
          Back to your workspace
        </Link>
      </header>

      {isVerified ? (
        <Notice kind="success">Your PAN is verified. Tax certificates for your donations will be emailed to you.</Notice>
      ) : hasPending ? (
        <p className="rounded border border-dashed border-line bg-white p-4 text-sm text-muted">
          Your submission is awaiting review. You will see the decision here once a reviewer has checked it.
        </p>
      ) : null}

      {subs.length > 0 && (
        <ul className="space-y-4" aria-label="Your PAN verification submissions">
          {subs.map((sub) => (
            <li key={sub.id} className="space-y-3 rounded-sm border-2 border-line bg-white p-5">
              <div className="flex flex-wrap items-start justify-between gap-3">
                <div>
                  <p className="font-medium text-navy">PAN: {sub.pan_number}</p>
                  <p className="text-sm text-muted">
                    {sub.original_filename} · {formatSize(sub.size_bytes)} · submitted {formatDate(sub.uploaded_at)}
                  </p>
                </div>
                <ReviewBadge status={sub.review_status} />
              </div>
              <p className="text-sm">{statusCopy(sub)}</p>
              {sub.latest_decision && (
                <blockquote className="border-l-2 border-line pl-3 text-sm">
                  <span className="font-medium">Reviewer&apos;s note:</span> {sub.latest_decision.reason}
                </blockquote>
              )}
              <button type="button" onClick={() => toggleHistory(sub)} aria-expanded={!!history[sub.id]}
                className="rounded-sm border-2 border-line px-3 py-1.5 text-sm font-display font-medium text-navy">
                {history[sub.id] ? "Hide review history" : "Review history"}
              </button>
              {history[sub.id] === "loading" && <p className="text-sm text-muted">Loading history…</p>}
              {history[sub.id] === "error" && <Notice kind="error">Could not load the review history.</Notice>}
              {Array.isArray(history[sub.id]) && <HistoryList rows={history[sub.id] as Decision[]} />}
            </li>
          ))}
        </ul>
      )}

      {!isVerified && (
        <section aria-labelledby="pan-upload-heading" className="space-y-5 border-t border-line pt-8">
          <h2 id="pan-upload-heading" className="text-lg font-semibold text-navy">
            {subs.length === 0 ? "Submit your PAN for verification" : "Submit again"}
          </h2>
          <form onSubmit={onUpload} className="grid gap-5 md:grid-cols-2">
            <label className="block">
              <span className="text-sm font-medium">PAN number</span>
              <input required maxLength={10} value={panNumber} onChange={(e) => setPanNumber(e.target.value)}
                placeholder="ABCDE1234F"
                className="mt-1 w-full rounded-sm border-2 border-line bg-white px-3 py-2 uppercase" />
            </label>
            <label className="block">
              <span className="text-sm font-medium">PAN card scan (PDF, JPEG or PNG, 10 MB at most)</span>
              <input key={fileInputKey} type="file" accept={ACCEPT} required
                onChange={(e) => setFile(e.target.files?.[0] ?? null)}
                className="mt-1 block w-full text-sm" />
            </label>
            <div className="md:col-span-2">
              <button type="submit" disabled={uploading}
                className="rounded-sm bg-teal px-4 py-2 font-display font-medium text-paper disabled:opacity-60">
                {uploading ? "Submitting…" : "Submit for verification"}
              </button>
            </div>
          </form>
          {uploadOk && <Notice kind="success">{uploadOk}</Notice>}
          {uploadError && <Notice kind="error">{uploadError}</Notice>}
        </section>
      )}
    </div>
  );
}

function HistoryList({ rows }: { rows: Decision[] }) {
  if (rows.length === 0) return <p className="text-sm text-muted">No reviews yet.</p>;
  return (
    <ol className="space-y-2 text-sm" aria-label="Review history, oldest first">
      {rows.map((r) => (
        <li key={r.id} className="rounded-sm bg-paper p-3">
          <span className="font-medium">{r.decision === "APPROVED" ? "Approved" : "Not accepted"}</span>
          <span className="text-muted"> on {formatDate(r.decided_at)}</span>
          <p className="mt-1">{r.reason}</p>
        </li>
      ))}
    </ol>
  );
}
